#!/usr/bin/env python3
"""Generate the 1.14d packet registry table.

Scans src/backends/lod114d/packets/{client,server} for packet classes, reads each
one's `static constexpr uint8_t ID`, and writes packets/RegistryTable.inc: the
headers, then one X-macro row per class that Registry.cpp expands into its
factory and size tables.

    python scripts/gen_packet_registry.py           # rewrite the table
    python scripts/gen_packet_registry.py --check   # fail if it is out of date

Fails (non-zero exit, nothing written) on two classes with one id in the same
direction, a header with no packet class, or a class whose id it cannot read.
"""

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKETS_DIR = REPO_ROOT / "src" / "backends" / "lod114d" / "packets"
TABLE = PACKETS_DIR / "RegistryTable.inc"

CLASS_RE = re.compile(r"^class\s+(\w+Packet)\s*:\s*public\s+Packet\b", re.M)
ID_RE = re.compile(r"static\s+constexpr\s+uint8_t\s+ID\s*=\s*(0[xX][0-9a-fA-F]+|\d+)\s*;")

HEADER = """// Generated by scripts/gen_packet_registry.py - do not edit.
//
// Every 1.14d packet class: first the headers, then one LOD114D_CLIENT_PACKET(id, Class) or
// LOD114D_SERVER_PACKET(id, Class) row per class. Define either macro before including this file (both default to
// nothing); the file undefines them again, so it can be included once per table it builds.

#ifndef LOD114D_CLIENT_PACKET
#define LOD114D_CLIENT_PACKET(id, name)
#endif

#ifndef LOD114D_SERVER_PACKET
#define LOD114D_SERVER_PACKET(id, name)
#endif

#ifndef LOD114D_PACKET_HEADERS_INCLUDED
#define LOD114D_PACKET_HEADERS_INCLUDED
"""

FOOTER = """
#undef LOD114D_CLIENT_PACKET
#undef LOD114D_SERVER_PACKET
"""


def scan(direction):
    """[(id, class, header)] for one direction, sorted by id, and the errors found."""
    found, errors = [], []
    for header in sorted((PACKETS_DIR / direction).glob("*.h")):
        text = header.read_text(encoding="utf-8")
        classes = CLASS_RE.findall(text)
        ids = ID_RE.findall(text)
        if not classes:
            errors.append(f"{header.name}: no packet class")
            continue
        if len(classes) != 1 or len(ids) != 1:
            errors.append(f"{header.name}: expected one packet class with one ID, found {len(classes)} / {len(ids)}")
            continue
        found.append((int(ids[0], 0), classes[0], f"packets/{direction}/{header.name}"))
    found.sort()
    seen = {}
    for packet_id, name, _ in found:
        if packet_id in seen:
            errors.append(f"{direction} id {packet_id:#04x}: both {seen[packet_id]} and {name}")
        seen[packet_id] = name
    return found, errors


def render():
    client, client_errors = scan("client")
    server, server_errors = scan("server")
    errors = client_errors + server_errors
    if errors:
        raise SystemExit("gen_packet_registry: " + "\n  ".join(["errors:", *errors]))
    lines = [HEADER]
    lines += [f'#include "{header}"' for _, _, header in client + server]
    lines.append("#endif  // LOD114D_PACKET_HEADERS_INCLUDED\n")
    lines += [f"LOD114D_CLIENT_PACKET({packet_id:#04x}, {name})" for packet_id, name, _ in client]
    lines.append("")
    lines += [f"LOD114D_SERVER_PACKET({packet_id:#04x}, {name})" for packet_id, name, _ in server]
    lines.append(FOOTER)
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the table is out of date instead of writing it")
    args = parser.parse_args()
    text = render()
    current = TABLE.read_text(encoding="utf-8") if TABLE.exists() else None
    if args.check:
        if current != text:
            print(f"{TABLE.relative_to(REPO_ROOT)} is out of date; run scripts/gen_packet_registry.py", file=sys.stderr)
            return 1
        return 0
    if current != text:
        TABLE.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
